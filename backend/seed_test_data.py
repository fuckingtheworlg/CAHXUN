def seed():
    conn = mysql.connector.connect(**DB_CONFIG)
    cursor = conn.cursor()

    now = datetime.now()
    inserted = 0

    for content, category in POSTS:
        days_ago = random.randint(0, 60)
        hours_ago = random.randint(0, 23)
        created_at = now - timedelta(days=days_ago, hours=hours_ago)

        images = ""
        if random.random() < 0.3:
            n = random.randint(1, 3)
            imgs = [f"https://picsum.photos/seed/{random.randint(1000,9999)}/400/300" for _ in range(n)]
            images = ",".join(imgs)

        cursor.execute(
            "INSERT INTO posts (content, images, created_at, category) VALUES (%s, %s, %s, %s)",
            (content, images or None, created_at, category),
        )
        inserted += 1

    conn.commit()
    cursor.close()
    conn.close()
    print(f"Done! Inserted {inserted} test posts.")


if __name__ == "__main__":
    seed()
